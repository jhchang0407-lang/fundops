@router.get("/outcomes")
async def get_outcomes(ticker: str = None, limit: int = 50):
    """Get recent outcome snapshots tracking how screened stocks performed.

    Outcome snapshots are recorded at intervals (90d, 180d, 365d, etc.)
    after stocks are screened. Returns price performance vs benchmark.
    """
    db = _get_db()
    try:
        outcomes = db.get_outcomes_for_strategy(ticker=ticker, limit=limit)

        # Compute alpha for each outcome
        enriched = []
        for o in outcomes:
            return_pct = o.get("return_pct")
            benchmark_pct = o.get("benchmark_return_pct")
            alpha = None
            if return_pct is not None and benchmark_pct is not None:
                alpha = round(return_pct - benchmark_pct, 2)

            enriched.append({
                "ticker": o.get("ticker"),
                "screener_run_id": o.get("screener_run_id"),
                "screened_at": o.get("screened_at"),
                "check_at": o.get("check_at"),
                "days_elapsed": o.get("days_elapsed"),
                "return_pct": return_pct,
                "benchmark_return_pct": benchmark_pct,
                "alpha_pct": alpha,
                "price_at_screen": o.get("price_at_screen"),
                "price_at_check": o.get("price_at_check"),
                "thesis_integrity": o.get("thesis_integrity"),
                "goal_alignment": o.get("goal_alignment"),
            })

        return {
            "outcomes": enriched,
            "count": len(enriched),
        }

    except Exception as e:
        log.error(f"Failed to fetch outcomes: {e}")
        raise HTTPException(500, f"Failed to fetch outcomes: {e}")
    finally:
        db.close()


