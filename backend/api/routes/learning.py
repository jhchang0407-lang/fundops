"""Learning API routes — surface refinement proposals, behavioral drift, and outcomes.

Exposes the learning loop subsystem (feedback patterns, proposal review,
behavioral drift, outcome snapshots, library similarity) as HTTP endpoints
for the frontend Learning page.
"""

import logging
from pathlib import Path
from fastapi import APIRouter, HTTPException
from fastapi.responses import JSONResponse
from pydantic import BaseModel
from typing import Optional

from backend.api.deps import get_config, get_llm
from backend.core.db_v2 import ScreenerV2DB

router = APIRouter(prefix="/learning", tags=["learning"])
log = logging.getLogger("fundops.api.learning")


def _get_db() -> ScreenerV2DB:
    """Get the v2 database instance."""
    config = get_config()
    db_path = config.resolved.get("db_path", str(Path.home() / ".fundops" / "fundops.db"))
    return ScreenerV2DB(db_path=db_path)


# ---------------------------------------------------------------------------
# GET /learning/proposals — pending refinement proposals + stats
# ---------------------------------------------------------------------------

@router.get("/proposals")
async def get_proposals():
    """Get pending refinement proposals and aggregate stats.

    Returns proposals generated by the feedback loop (Loop 1) that
    are awaiting user accept/reject, plus overall proposal stats.
    """
    db = _get_db()
    try:
        constitution = db.get_active_constitution()
        constitution_id = constitution.get("id") if constitution else None
        proposals = db.get_pending_proposals(constitution_id=constitution_id)
        stats = db.get_proposal_stats()
    except Exception as e:
        log.error(f"Failed to fetch proposals: {e}")
        db.close()
        raise HTTPException(500, f"Failed to fetch proposals: {e}")
    finally:
        db.close()

    return {
        "proposals": proposals,
        "stats": stats,
        "count": len(proposals),
    }


# ---------------------------------------------------------------------------
# POST /learning/proposals/{proposal_id} — accept or reject a proposal
# ---------------------------------------------------------------------------

class ProposalAction(BaseModel):
    action: str  # "accept" or "reject"
    reason: Optional[str] = None


@router.post("/proposals/{proposal_id}")
async def resolve_proposal(proposal_id: str, body: ProposalAction):
    """Accept or reject a refinement proposal.

    Accept flow:
      1. Generate refined scoring code from the proposal (requires LLM)
      2. Create a new strategy version with the refined code
      3. Update the constitution's active_version_id
      4. Mark proposal as accepted with the new version id

    Reject flow:
      1. Mark proposal as rejected with optional reason
    """
    if body.action not in ("accept", "reject"):
        raise HTTPException(400, "action must be 'accept' or 'reject'")

    db = _get_db()
    try:
        proposal = db.get_proposal(proposal_id)
        if not proposal:
            raise HTTPException(404, f"Proposal {proposal_id} not found")

        if proposal.get("status") != "pending":
            raise HTTPException(
                409, f"Proposal {proposal_id} already resolved with status '{proposal.get('status')}'"
            )

        if body.action == "reject":
            updated = db.resolve_proposal(proposal_id, user_response="rejected")
            log.info(f"Proposal {proposal_id} rejected. Reason: {body.reason or 'none'}")
            return {"proposal": updated, "action": "rejected"}

        # --- Accept flow ---
        # Get current scoring code from the active version
        constitution = db.get_active_constitution()
        active_version_id = constitution.get("active_version_id") if constitution else None
        current_code = ""
        if active_version_id:
            version = db.get_version(active_version_id)
            if version:
                current_code = version.get("scoring_code", "")

        if not current_code:
            # No existing scoring code — accept the proposal but skip code generation
            updated = db.resolve_proposal(proposal_id, user_response="accepted")
            log.info(f"Proposal {proposal_id} accepted (no active scoring code to refine)")
            return {
                "proposal": updated,
                "action": "accepted",
                "note": "No active scoring code found — proposal recorded but no code generated.",
            }

        # Generate refined code using LLM
        # TODO: This requires an async LLM call. For now, attempt it and fall back gracefully.
        try:
            from backend.learning.feedback_loop import generate_refined_code

            llm = get_llm()
            strategy = None
            if constitution:
                strategy = {
                    "north_star": constitution.get("north_star"),
                    "style_identity": constitution.get("style_identity"),
                    "must_have_signals": constitution.get("must_have_signals"),
                    "anti_signals": constitution.get("anti_signals"),
                }

            new_code = await generate_refined_code(llm, current_code, proposal, strategy)

            if new_code:
                # Create a new strategy version
                import uuid
                new_version_id = f"v-{uuid.uuid4().hex[:8]}"
                constitution_id = constitution.get("id") if constitution else None

                # Determine strategy_id and version_number
                strategy_id = constitution_id or "default"
                current_version = db.get_version(active_version_id)
                version_number = (current_version.get("version_number", 0) + 1) if current_version else 1

                version_row = db.create_version(
                    version_id=new_version_id,
                    strategy_id=strategy_id,
                    version_number=version_number,
                    scoring_code=new_code,
                    label_map=current_version.get("label_map") if current_version else None,
                    explanation=f"Refined from proposal {proposal_id}: {proposal.get('proposal', '')}",
                )
                actual_vid = version_row["id"] if version_row else new_version_id

                # Activate the new version on the constitution
                if constitution_id:
                    db.update_constitution(constitution_id, active_version_id=actual_vid)

                updated = db.resolve_proposal(
                    proposal_id, user_response="accepted", applied_version_id=actual_vid
                )
                log.info(f"Proposal {proposal_id} accepted. New version: {actual_vid}")
                return {
                    "proposal": updated,
                    "action": "accepted",
                    "new_version_id": actual_vid,
                }
            else:
                # Code generation failed validation — do NOT mark as accepted
                log.warning(f"Proposal {proposal_id}: code generation failed validation")
                return JSONResponse(
                    status_code=500,
                    content={
                        "error": "Code generation failed validation",
                        "detail": "Proposal was not accepted because refined code could not be generated.",
                    },
                )

        except Exception as e:
            # Code generation error — do NOT mark as accepted
            log.warning(f"Code generation failed for proposal {proposal_id}: {e}")
            return JSONResponse(
                status_code=500,
                content={
                    "error": "Code generation failed",
                    "detail": f"Proposal was not accepted: {e}",
                },
            )

    except HTTPException:
        raise
    except Exception as e:
        log.error(f"Failed to resolve proposal {proposal_id}: {e}")
        raise HTTPException(500, f"Failed to resolve proposal: {e}")
    finally:
        db.close()


