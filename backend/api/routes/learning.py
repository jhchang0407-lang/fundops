@router.get("/drift")
async def get_drift():
    """Get behavioral drift analysis: stated constitution vs actual IC decisions.

    Requires at least 5 IC decisions to produce meaningful analysis.
    Returns empty result with a message if insufficient data.
    """
    db = _get_db()
    try:
        constitution = db.get_active_constitution()
        if not constitution:
            return {
                "has_enough_data": False,
                "decisions_analyzed": 0,
                "summary": "No active constitution found. Create a strategy first.",
                "style_drift": [],
                "signal_drift": [],
                "anti_signal_violations": [],
                "override_patterns": [],
                "approval_profile": {},
            }

        from backend.learning.behavioral import analyze_drift

        drift = await analyze_drift(db, constitution)
        return drift

    except Exception as e:
        log.error(f"Drift analysis failed: {e}")
        raise HTTPException(500, f"Drift analysis failed: {e}")
    finally:
        db.close()


