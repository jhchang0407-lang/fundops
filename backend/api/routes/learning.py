# This router is mounted under /api with prefix /learning, so we need
# a separate router for library endpoints at the module level, or we
# include it here with an overridden path. We use the learning router
# but with a full path override.

library_router = APIRouter(prefix="/library", tags=["library"])


class SimilarRequest(BaseModel):
    ticker: str
    sector: Optional[str] = None
    gross_margin: Optional[float] = None
    roic: Optional[float] = None
    top_k: int = 5


@library_router.post("/similar")
async def find_similar(body: SimilarRequest):
    """Find similar library entries by sector and financial metrics.

    Uses SQL-based similarity matching on sector, gross margin range (+/-10pp),
    and ROIC range (+/-5pp). Returns up to top_k matches.
    """
    db = _get_db()
    try:
        results = db.find_similar(
            ticker=body.ticker,
            sector=body.sector,
            gross_margin=body.gross_margin,
            roic=body.roic,
            top_k=body.top_k,
        )
        return {
            "query": {
                "ticker": body.ticker,
                "sector": body.sector,
                "gross_margin": body.gross_margin,
                "roic": body.roic,
            },
            "results": results,
            "count": len(results),
        }

    except Exception as e:
        log.error(f"Library similarity search failed: {e}")
        raise HTTPException(500, f"Library similarity search failed: {e}")
    finally:
        db.close()


class LibraryAskRequest(BaseModel):
    question: str
    history: list = []


@library_router.post("/ask")
async def ask_library(body: LibraryAskRequest):
    """Ask questions about your research archive using AI.

    Gathers relevant library data (thesis, IC, memos, events) and sends
    the question + context to the LLM for an informed answer.
    """
    import json as _json
    import re

    from backend.api.deps import get_llm, get_db as get_main_db

    llm = get_llm()
    if not llm.api_key:
        return {
            "answer": "AI model not configured. Set up your API key in Settings to enable Library Q&A.",
            "sources": [],
        }

    db = _get_db()
    main_db = get_main_db()

    # Extract ticker mentions from the question
    ticker_pattern = re.compile(r'\b([A-Z]{1,6})\b')
    mentioned_tickers = ticker_pattern.findall(body.question)
    # Filter out common words that look like tickers
    common_words = {"THE", "AND", "FOR", "NOT", "BUT", "ALL", "ARE", "WAS", "HAS", "HAD", "HOW", "WHY", "DID", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC", "JAN", "FEB", "MAR"}
    mentioned_tickers = [t for t in mentioned_tickers if t not in common_words]

    # Gather context from the library
    context_parts = []

    # 1. Get library stats
    try:
        stats = db.get_library_stats()
        context_parts.append(f"Library stats: {_json.dumps(stats, default=str)}")
    except Exception:
        pass

    # 2. Get data for mentioned tickers
    for ticker in mentioned_tickers[:5]:  # Max 5 tickers
        try:
            entries = db.get_library_by_ticker(ticker)
            if entries:
                for entry in entries[:3]:  # Max 3 entries per ticker
                    entry_data = entry.get("data", {})
                    if isinstance(entry_data, str):
                        try:
                            entry_data = _json.loads(entry_data)
                        except Exception:
                            pass
                    context_parts.append(
                        f"\n--- {ticker} ({entry.get('entry_type', '?')}, verdict={entry.get('verdict', '?')}) ---\n"
                        f"Expected return: {entry.get('expected_return')}%, "
                        f"Discount: {entry.get('discount_pct')}%, "
                        f"Conviction: {entry.get('conviction')}, "
                        f"Sector: {entry.get('sector')}, "
                        f"GM: {entry.get('gross_margin')}, ROIC: {entry.get('roic')}"
                    )

            # Also get agent runs for this ticker (thesis narrative, IC review)
            runs = main_db.get_runs_for_ticker(ticker) if hasattr(main_db, 'get_runs_for_ticker') else []
            for run in (runs if isinstance(runs, list) else [])[:5]:
                agent = run.get("agent", "")
                run_type = run.get("run_type", "")
                if run_type in ("job_start", "job_complete"):
                    continue
                try:
                    fo = run.get("full_output")
                    full = _json.loads(fo) if isinstance(fo, str) else (fo or {})
                    if agent == "thesis":
                        narrative = full.get("thesis_narrative", "")
                        if narrative:
                            context_parts.append(f"\n--- {ticker} THESIS ---\n{narrative[:1500]}")
                    elif agent == "ic_review":
                        review = full.get("ai_review", "")
                        verdict = full.get("verdict", "")
                        if review:
                            context_parts.append(f"\n--- {ticker} IC REVIEW ({verdict}) ---\n{review[:1000]}")
                    elif agent == "memo":
                        summary = run.get("summary", "")
                        if summary:
                            context_parts.append(f"\n--- {ticker} MEMO ---\n{summary[:500]}")
                except Exception:
                    pass
        except Exception:
            pass

    # 3. If no tickers mentioned, get recent events for general context
    if not mentioned_tickers:
        try:
            recent = db.get_recent_events(limit=20)
            for ev in (recent if isinstance(recent, list) else [])[:10]:
                context_parts.append(
                    f"{ev.get('event_type', '?')} {ev.get('ticker', '?')}: {ev.get('rationale', '')[:100]}"
                )
        except Exception:
            pass

    # Build the prompt
    context_text = "\n".join(context_parts) if context_parts else "No research data available yet."

    system_prompt = """You are the FundOps Library AI assistant. You have access to the user's research archive including screener results, thesis narratives, IC review verdicts, investment memos, and outcome tracking data.

Answer questions about their research history, investment decisions, thesis assumptions, and portfolio analysis. Be specific with data when available. Reference actual numbers, verdicts, and dates from the context.

If the user asks about a ticker, use the thesis, IC review, and memo data provided. If they ask general questions, use the library stats and recent events."""

    messages = [{"role": "system", "content": system_prompt}]

    # Add conversation history
    for msg in body.history[-10:]:
        role = msg.get("role", "user")
        if role == "ai":
            role = "assistant"
        messages.append({"role": role, "content": msg.get("content", "")})

    # Add current question with context
    messages.append({
        "role": "user",
        "content": f"""RESEARCH CONTEXT:
{context_text[:6000]}

QUESTION: {body.question}"""
    })

    try:
        result = await llm.generate_chat(
            messages=messages,
            agent="library_qa",
            reasoning_effort="medium",
        )

        sources = []
        for t in mentioned_tickers[:5]:
            sources.append({"ticker": t, "type": "library_entry"})

        db.close()
        return {
            "answer": result.text or "I couldn't generate a response. Please try again.",
            "sources": sources,
            "tokens": result.tokens_in + result.tokens_out,
            "cost": round(result.cost, 4),
        }

    except Exception as e:
        log.error(f"Library Q&A failed: {e}")
        db.close()
        return {
            "answer": f"Failed to get AI response: {str(e)}",
            "sources": [],
        }
